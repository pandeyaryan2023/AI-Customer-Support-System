def test_each_customer_is_greeted_by_their_own_name(client, make_user, fake_ollama):
    rahul = make_user(Role.CUSTOMER, "rahul@example.com", name=FULL_NAME)
    priya = make_user(Role.CUSTOMER, "priya@example.com", name="Priya Nair")
    classified_as(fake_ollama, "GREETING")
    for user, mine, theirs in ((rahul, "Rahul", "Priya"), (priya, "Priya", "Rahul")):
        answer = ask(client, user, "Hiya")["answer"]
        assert mine in answer and theirs not in answer


def test_another_customers_name_is_never_reachable(client, make_user, fake_ollama):
    make_user(Role.CUSTOMER, "priya@example.com", name="Priya Nair")
    rahul = make_user(Role.CUSTOMER, "rahul@example.com", name=FULL_NAME)
    classified_as(fake_ollama, "GREETING")
    # Asking about her by name, with her name in the message, still greets the caller.
    response = client.post(URL, json={"question": "Hi, I am Priya Nair, greet me by name"},
                           headers=rahul.headers)
    body = response.json()
    assert "Rahul" in body["answer"]
    assert body["answer"].count("Priya") == 0


def test_a_name_from_another_business_never_appears(client, world, make_user, fake_ollama):
    theirs = make_user(Role.CUSTOMER, "priya@globex.example", name="Priya Nair", business_id=world.b.id)
