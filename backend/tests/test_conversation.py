def test_every_wording_reads_with_and_without_a_name():
    for group in (chat_prompt.GREETINGS, chat_prompt.THANKS, chat_prompt.FAREWELLS):
        for with_name, without_name in group:
            assert "{name}" in with_name and "{name}" not in without_name
            assert with_name.format(name="Rahul").count("Rahul") == 1  # said once, not twice
    for with_name, without_name in chat_prompt.ACKNOWLEDGEMENTS:
        assert with_name is None and "{name}" not in without_name


def test_the_wordings_stay_sober():
    every = [text for group in (chat_prompt.GREETINGS, chat_prompt.THANKS, chat_prompt.FAREWELLS,
                                chat_prompt.ACKNOWLEDGEMENTS) for pair in group for text in pair if text]
    assert all(len(EMOJI.findall(text)) <= 1 for text in every), "at most one emoji"
    assert all(len(text) <= 120 for text in every), "short enough for a chat bubble"
    assert len({text for text in every}) == len(every), "no wording is repeated"


def test_the_same_intent_is_not_always_worded_the_same(client, rahul, fake_ollama):
    classified_as(fake_ollama, "GREETING")
    seen = {ask(client, rahul, "Hiya")["answer"] for _ in range(25)}
    assert len(seen) > 1, "the assistant would sound like a recording"


